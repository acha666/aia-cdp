import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import {
  decimalFromHex,
  sha1Hex,
  sha256Hex,
  toDigestInput,
  toHex,
} from "../../../src/core/pki/conversion.ts";
import { parseCertificate } from "../../../src/core/pki/parsers.ts";
import { fixture, manifest } from "../../fixtures/pki.ts";

// worker-aia-cdp@5b570aa:tests/worker/conversion.test.ts. The serial literal is read from the
// manifest (hex, as `openssl x509 -serial` prints it), and the digests are checked on offset views.

const LEAF = manifest.certificates.find((c) => c.name === "leaf-full");
if (!LEAF) {
  throw new Error("no manifest entry for leaf-full");
}
const LEAF_DER = fixture(LEAF.der);

function nodeDigest(algorithm: "sha1" | "sha256", bytes: Uint8Array): string {
  return createHash(algorithm).update(bytes).digest("hex");
}

/** `bytes` in the middle of a larger buffer filled with other bytes. */
function offsetView(bytes: Uint8Array): Uint8Array<ArrayBuffer> {
  const padded = new Uint8Array(bytes.length + 16).fill(0xa5);
  padded.set(bytes, 7);
  return padded.subarray(7, 7 + bytes.length);
}

describe("digests", () => {
  it("sha256Hex matches the digest generated by node:crypto and the manifest", async () => {
    expect(await sha256Hex(LEAF_DER)).toBe(nodeDigest("sha256", LEAF_DER));
    expect(await sha256Hex(LEAF_DER)).toBe(LEAF.sha256);
  });

  it("sha256Hex and sha1Hex hash only the bytes of a view", async () => {
    const view = offsetView(LEAF_DER);
    expect(await sha256Hex(view)).toBe(LEAF.sha256);
    expect(await sha1Hex(view)).toBe(nodeDigest("sha1", LEAF_DER));
    expect(await sha1Hex(LEAF_DER.buffer)).toBe(nodeDigest("sha1", LEAF_DER));
  });
});

describe("toDigestInput", () => {
  it("returns an ArrayBuffer-backed view itself, without copying", () => {
    const view = offsetView(LEAF_DER);
    expect(toDigestInput(view)).toBe(view);
  });

  it("wraps an ArrayBuffer", () => {
    const input = toDigestInput(LEAF_DER.buffer);
    expect(input.buffer).toBe(LEAF_DER.buffer);
    expect(input).toEqual(LEAF_DER);
  });

  it("copies a view of a SharedArrayBuffer into an ArrayBuffer", () => {
    const shared = new Uint8Array(new SharedArrayBuffer(LEAF_DER.length + 4));
    shared.set(LEAF_DER, 2);
    const view = shared.subarray(2, 2 + LEAF_DER.length);
    const input = toDigestInput(view);
    expect(input.buffer).toBeInstanceOf(ArrayBuffer);
    expect(Array.from(input)).toEqual(Array.from(LEAF_DER));
  });
});

describe("hex", () => {
  it("toHex converts binary to lower-case hex", () => {
    expect(toHex(Uint8Array.of(0x0a, 0x46, 0xa2))).toBe("0a46a2");
    expect(toHex(Uint8Array.of(0x0a, 0x46, 0xa2).buffer)).toBe("0a46a2");
  });

  it("decimalFromHex converts serial numbers from hex", () => {
    const serial = parseCertificate(LEAF_DER).serialNumber.toBigInt();
    expect(decimalFromHex(LEAF.serial)).toBe(serial.toString(10));
  });

  it("decimalFromHex returns null on invalid input", () => {
    expect(decimalFromHex("not-hex")).toBeNull();
    expect(decimalFromHex(null)).toBeNull();
  });
});
